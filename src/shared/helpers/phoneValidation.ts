/** Нормализует номер до 11 цифр с ведущей 7: "7XXXXXXXXXX". Возвращает null при невалидном формате. */
export function normalizePhone(raw: string): string | null {
  const digits = raw.replace(/\D/g, "");

  return /^7\d{10}$/.test(digits) ? digits : null;
}

/** Проверяет, что код оператора (первые 3 цифры после ведущей 7) принадлежит оператору РФ. */
export function isRfDefCode(normalizedPhone: string): boolean {
  return RF_DEF_CODES.includes(normalizedPhone.slice(1, 4));
}